#!/usr/bin/env node
// Builds dist/ from src/ and data/:
//   1. Checks data/domains.json against data/SOURCE.json.
//   2. Writes src/data.generated.ts with the fields that lookup() needs.
//   3. Compiles ESM (dist/esm) and CommonJS (dist/cjs) with tsc.
//   4. Copies data/domains.json to ./domains.json for the "agent-email-domains/domains.json" export.
import { readFileSync, writeFileSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "../..");
const text = readFileSync(join(ROOT, "data/domains.json"), "utf8");
const source = JSON.parse(readFileSync(join(ROOT, "data/SOURCE.json"), "utf8"));

if (createHash("sha256").update(text).digest("hex") !== source.sha256) {
  console.error("error: data/domains.json does not match data/SOURCE.json. Run: node scripts/sync-list.mjs --latest");
  process.exit(1);
}

const rows = JSON.parse(text).map((entry) => `  ${JSON.stringify([entry.domain, entry.provider, entry.category])},`);
writeFileSync(
  join(ROOT, "src/data.generated.ts"),
  `// Generated by scripts/build.mjs from revdoku/agent-email-domains v${source.list_version}. Do not edit.
import type { Category } from "./index.js";

export const listVersion: string = ${JSON.stringify(source.list_version)};

export const data: ReadonlyArray<readonly [domain: string, provider: string, category: Category]> = [
${rows.join("\n")}
];
`,
);

const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
rmSync(join(ROOT, "dist"), { recursive: true, force: true });
execFileSync(process.execPath, [tsc, "-p", "tsconfig.json"], { cwd: ROOT, stdio: "inherit" });
execFileSync(process.execPath, [tsc, "-p", "tsconfig.cjs.json"], { cwd: ROOT, stdio: "inherit" });
writeFileSync(join(ROOT, "dist/cjs/package.json"), `${JSON.stringify({ type: "commonjs" })}\n`);
writeFileSync(join(ROOT, "domains.json"), text);
console.log(`dist/: list v${source.list_version}, ${rows.length} domains`);
