#!/usr/bin/env node
// Writes src/data.generated.ts from data/domains.json after checking it against data/SOURCE.json.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "../..");
const text = readFileSync(join(ROOT, "data/domains.json"), "utf8");
const source = JSON.parse(readFileSync(join(ROOT, "data/SOURCE.json"), "utf8"));

if (createHash("sha256").update(text).digest("hex") !== source.sha256) {
  console.error("error: data/domains.json does not match data/SOURCE.json. Run: node scripts/sync-list.mjs --latest");
  process.exit(1);
}

const entries = JSON.parse(text);
const output = `// Generated by scripts/generate.mjs from revdoku/agent-email-domains v${source.list_version}. Do not edit.
import type { DomainEntry } from "./types.js";

export const listVersion = ${JSON.stringify(source.list_version)};

const data: DomainEntry[] = [
${entries.map((entry) => `  ${JSON.stringify(entry)},`).join("\n")}
];

export const entries: readonly DomainEntry[] = Object.freeze(data.map((entry) => Object.freeze(entry)));
`;

writeFileSync(join(ROOT, "src/data.generated.ts"), output);
console.log(`src/data.generated.ts: list v${source.list_version}, ${entries.length} domains`);
